#!/usr/bin/env python3
"""Generate src/text/unicode_tables.h from Python's unicodedata.

Development only (AGENTS.md: Python under tools/dev/ and tests/golden/,
never at runtime). The output is committed; rerun only with the golden
environment, whose Python and tokenizers versions are pinned:

    tests/golden/.venv/bin/python -I tools/dev/gen_unicode.py > src/text/unicode_tables.h

Tables (all sorted, searched by binary search in src/text/unicode.c):

  classes        ranges of code points in the classes pre-tokenization needs:
                 L (letters), M (marks), N (numbers), S (white space as
                 Oniguruma's \\s: U+0009..U+000D, U+0085, Zs, Zl, Zp)
  ccc            ranges with a non-zero canonical combining class
  decomp         full canonical decomposition of every code point that has
                 one (Hangul syllables excluded: they are algorithmic)
  compose        primary composites: the pair a, b that composes to c

The classes follow Python's Unicode version, which is the one the
reference tokenizer's regex engine (Oniguruma) uses. Normalization does
not: Hugging Face tokenizers normalizes with older Unicode data (9.0 in
tokenizers 0.23), which lacks the combining classes and compositions of
characters added since. The normalization tables therefore keep only what
the reference applies, found by running its NFC and NFD on every entry:
a combining class the reference ignores is 0, a decomposition or a
composition it does not perform is left out.
"""
import platform
import sys
import unicodedata

from tokenizers import __version__ as tokenizers_version
from tokenizers.normalizers import NFC, NFD

hf_nfc = NFC().normalize_str
hf_nfd = NFD().normalize_str

MAX = 0x110000
SURROGATES = range(0xD800, 0xE000)


def cls(c):
    ch = chr(c)
    cat = unicodedata.category(ch)
    if cat[0] == "L":
        return 1
    if cat[0] == "M":
        return 2
    if cat[0] == "N":
        return 3
    if c in (0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x85) or cat in ("Zs", "Zl", "Zp"):
        return 4
    return 0


def ranges(value):
    out = []
    start, cur = 0, value(0)
    for c in range(1, MAX + 1):
        v = value(c) if c < MAX else None
        if v != cur:
            if cur:
                out.append((start, c - 1, cur))
            start, cur = c, v
    return out


def is_hangul_syllable(c):
    return 0xAC00 <= c <= 0xD7A3


# Marks of different combining classes (230, 220, 10, 107, 8, 1): a mark
# whose class the reference knows is ordered against them as Python orders it.
PROBES = ("\u0301", "\u0323", "\u05b0", "\u0e48", "\u3099", "\u0334")


def reference_knows_ccc(c):
    for m in PROBES:
        for s in ("a" + m + chr(c), "a" + chr(c) + m):
            if hf_nfc(s) != unicodedata.normalize("NFC", s):
                return False
    return True


def main():
    o = sys.stdout
    o.write("/* unicode_tables.h: GENERATED by tools/dev/gen_unicode.py, do not edit.\n")
    o.write(f" * Unicode {unicodedata.unidata_version} (Python {platform.python_version()} unicodedata); normalization\n")
    o.write(f" * limited to what Hugging Face tokenizers {tokenizers_version} applies (gen_unicode.py).\n")
    o.write(" * Included by src/text/unicode.c only. */\n")
    o.write("#ifndef ATH_UNICODE_TABLES_H\n#define ATH_UNICODE_TABLES_H\n\n")
    o.write(f'#define ATH_UNICODE_VERSION "{unicodedata.unidata_version}"\n\n')
    o.write("typedef struct { uint32_t lo, hi; uint8_t v; } uc_range;\n")
    o.write("typedef struct { uint32_t cp; uint16_t off; uint8_t len; } uc_decomp;\n")
    o.write("typedef struct { uint32_t a, b, c; } uc_pair;\n\n")

    def class_of(c):
        return 0 if c in SURROGATES else cls(c)

    def ccc_of(c):
        if c in SURROGATES:
            return 0
        k = unicodedata.combining(chr(c))
        return k if k and reference_knows_ccc(c) else 0

    for name, table in (("uc_classes", ranges(class_of)), ("uc_ccc", ranges(ccc_of))):
        o.write(f"static const uc_range {name}[{len(table)}] = {{\n")
        for i in range(0, len(table), 4):
            o.write("    " + " ".join("{0x%X, 0x%X, %d}," % r for r in table[i:i + 4]) + "\n")
        o.write("};\n\n")

    pool, decomp = [], []
    for c in range(MAX):
        if c in SURROGATES or is_hangul_syllable(c):
            continue
        d = unicodedata.decomposition(chr(c))
        if not d or d.startswith("<"):
            continue
        if hf_nfd(chr(c)) != unicodedata.normalize("NFD", chr(c)):
            continue   # a decomposition the reference does not know
        full = [ord(x) for x in unicodedata.normalize("NFD", chr(c))]
        decomp.append((c, len(pool), len(full)))
        pool.extend(full)
    assert len(pool) < 65536 and max(n for _, _, n in decomp) < 256
    o.write(f"static const uint32_t uc_decomp_pool[{len(pool)}] = {{\n")
    for i in range(0, len(pool), 8):
        o.write("    " + " ".join("0x%X," % x for x in pool[i:i + 8]) + "\n")
    o.write("};\n\n")
    o.write(f"static const uc_decomp uc_decomp_index[{len(decomp)}] = {{\n")
    for i in range(0, len(decomp), 4):
        o.write("    " + " ".join("{0x%X, %d, %d}," % d for d in decomp[i:i + 4]) + "\n")
    o.write("};\n\n")

    pairs = []
    for c in range(MAX):
        if c in SURROGATES or is_hangul_syllable(c):
            continue
        d = unicodedata.decomposition(chr(c))
        if not d or d.startswith("<"):
            continue
        parts = [int(x, 16) for x in d.split()]
        if len(parts) != 2:
            continue
        pair = chr(parts[0]) + chr(parts[1])
        if unicodedata.normalize("NFC", pair) == chr(c) and hf_nfc(pair) == chr(c):
            pairs.append((parts[0], parts[1], c))
    pairs.sort()
    o.write(f"static const uc_pair uc_compose[{len(pairs)}] = {{\n")
    for i in range(0, len(pairs), 4):
        o.write("    " + " ".join("{0x%X, 0x%X, 0x%X}," % p for p in pairs[i:i + 4]) + "\n")
    o.write("};\n\n#endif /* ATH_UNICODE_TABLES_H */\n")


if __name__ == "__main__":
    main()
